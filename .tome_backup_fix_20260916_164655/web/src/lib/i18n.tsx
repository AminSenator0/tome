interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  tGenre: (genre?: string) => string
  tStatus: (status?: string) => string
  formatNumber: (n: number, opts?: Intl.NumberFormatOptions) => string
  formatDate: (ts: number) => string
  formatDateTime: (ts: number) => string
  locale: string
  isRtl: boolean
}

const Ctx = createContext<I18nCtx>({
  lang: 'en',
  setLang: () => undefined,
  t: (k: string) => k,
  tGenre: (g?: string) => g ?? '',
  tStatus: (s?: string) => s ?? '',
  formatNumber: (n: number) => String(n),
  formatDate: () => '—',
  formatDateTime: () => '—',
  locale: 'en-US',
  isRtl: false,
})

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem('tome_lang') === 'fa' ? 'fa' : 'en'
    } catch {
      return 'en'
    }
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('tome_lang', l)
    } catch {
      /* ignore */
    }
  }, [])

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = DICT[lang][key] ?? DICT.en[key] ?? key
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
        }
      }
      return s
    },
    [lang]
  )

  const tGenre = useCallback(
    (genre?: string) => {
      const k = (genre || 'general').toLowerCase()
      return GENRE_DICT[lang][k] ?? GENRE_DICT.en[k] ?? genre ?? ''
    },
    [lang]
  )

  const tStatus = useCallback(
    (status?: string) => {
      const k = (status || '').toLowerCase()
      return STATUS_DICT[lang][k] ?? STATUS_DICT.en[k] ?? status ?? ''
    },
    [lang]
  )

  const locale = lang === 'fa' ? 'fa-IR' : 'en-US'
  const isRtl = lang === 'fa'

  const formatNumber = useCallback(
    (n: number, opts?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(locale, { maximumFractionDigits: 0, ...opts }).format(n),
    [locale]
  )

  const formatDate = useCallback(
    (ts: number) => {
      if (!ts) return '—'
      return new Date(ts * 1000).toLocaleString(locale, {
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
      })
    },
    [locale]
  )

  const formatDateTime = formatDate

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr'
  }, [lang, isRtl])

  return (
    <Ctx.Provider
      value={{ lang, setLang, t, tGenre, tStatus, formatNumber, formatDate, formatDateTime, locale, isRtl }}
    >
      {children}
    </Ctx.Provider>
  )
}

export const useI18n = () => useContext(Ctx)
